    fun hasCyrillic(str: String?): Boolean {
        if (str.isNullOrBlank()) return false
        return str.any { it in 'Ѐ'..'ӿ' }
    }

    /**
     * Resolves the official Russian title for an anime.
     * 1. If currentRussian is already valid Russian with Cyrillic, prefer known official Shikimori title or keep it.
     * 2. If currentRussian is missing, empty, or Latin only, fetch the authentic Russian title.
     */
    fun resolveRussianTitle(animeId: Long?, currentRussian: String?, name: String?): String {
        if (animeId != null && animeId > 0) {
            val known = knownRussianTitlesById[animeId]
            if (!known.isNullOrBlank()) {
                return known
            }
        }
        if (!currentRussian.isNullOrBlank() && hasCyrillic(currentRussian)) {
            return currentRussian.trim()
        }
        return currentRussian?.takeIf { it.isNotBlank() } ?: (name?.trim() ?: "")
    }
