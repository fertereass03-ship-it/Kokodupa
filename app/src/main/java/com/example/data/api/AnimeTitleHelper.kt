    fun getDisplayTitle(anime: ShikimoriAnimeDto): String {
        return getLocalizedTitle(anime.id, anime.russian, anime.name)
    }

    fun getLocalizedTitle(animeId: Long, originalRussian: String?, name: String): String {
        val isUk = AppSettingsManager.isUkrainian()
        if (isUk) {
            UKRAINIAN_TITLES[animeId]?.let { return it }
            // If in Ukrainian mode, translate common Russian titles or adapt
            val ru = ShikimoriRussianTitles.resolveRussianTitle(animeId, originalRussian, name)
            return adaptRuToUk(ru, name)
        } else {
            return ShikimoriRussianTitles.resolveRussianTitle(animeId, originalRussian, name)
        }
    }

